"""Generate the source-controlled desktop Glauka Cloud browser module bundle.

Run from the repository root: python scripts/release/bundle_cloud_modules.py
Add --check to verify the committed copy without modifying it.
Only local files are read; no GitHub Actions or network calls.
"""
from __future__ import annotations
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = (
    "packages/cloud-sync/core.js",
    "packages/cloud-sync/hash.js",
    "packages/cloud-sync/providers.js",
)
OUTPUT = ROOT / "apps/desktop-shared/src/cloud_modules.js"


def bundle() -> str:
    header = (
        "// Generated by scripts/release/bundle_cloud_modules.py; do not edit directly.\n"
        "// Restricted desktop runtime: no OAuth tokens, no automatic syncing.\n"
    )
    parts = []
    for relative in SOURCES:
        source = (ROOT / relative).read_text(encoding="utf-8").strip()
        parts.append(f"// SOURCE: {relative}\n{source}\n")
    return header + "\n".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = bundle()
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print("Cloud desktop bundle is stale. Regenerate before release.", file=sys.stderr)
            sys.exit(1)
        print("Cloud desktop bundle is current.")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(expected)} characters)")
